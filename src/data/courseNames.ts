/**
 * その地域でのコース名。表に無い名前（新しく足したコース・大学駅伝など）はそのまま返す。
 * **地形は変わらない。変わるのは呼び名だけ。**
 */
export function courseNameFor(domesticName: string, region: CourseRegion): string {
  if (region === 'domestic') return domesticName
  return NAMES[region][domesticName] ?? domesticName
}

