import { natGeoRegion } from './nationalities'

// コースの呼び名を決める唯一の場所。
//
// ■なぜ要るのか（実際に起きていたこと）
//   コースの中身（区間の距離・登り・下り）は `data/races.ts` の25本しかない。
//   ところが**海外リーグも世界選手権も、その25本を名前ごとそのまま走っていた**。
//     ・ケニアのクラブが「出雲開幕戦」を走る
//     ・アメリカ大陸予選が「アメリカ予選 大阪カップ」になる
//   いずれ海外のクラブを指揮するので（CLAUDE.md）、これでは監督が移った先に
//   そのリーグの大会が1つも無いことになる。
//
// ■どう直すか
//   **中身は増やさない。名前だけを地域ごとに持つ。**
//   同じ地形なのでタイムはそのまま比べられ、記録表は地域ごとに分かれる。
//   コースを新しく足すより安くて、大会の数だけが増える。
//
// ■決まり
//   国内以外のレース名は必ず `courseNameFor` を通すこと。
//   `data/races.ts` の名前を国外のレースへ直接使うと `npm run check` が落ちる。

export type CourseRegion = 'domestic' | 'asia' | 'africa' | 'europe' | 'america'

/**
 * その国のクラブ・大会が走るときに使う地名の地域。
 * オセアニアはアジアと同じ組（世界選手権の地域分けと同じ）。
 * 日本開催は国内の名前をそのまま使う（日本でやる世界選手権は「出雲開幕戦」でよい）。
 */
export function courseRegionOfNation(nat: Nationality | undefined): CourseRegion {
  if (nat === 'JPN') return 'domestic'
  switch (natGeoRegion(nat as Nationality)) {
    case 'アフリカ': return 'africa'
    case 'ヨーロッパ': return 'europe'
    case 'アメリカ大陸': return 'america'
    case 'アジア': case 'オセアニア': return 'asia'
    default: return 'domestic'
  }
}

