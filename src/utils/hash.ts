/**
 * 文字列 → 決め打ちの数値。**このハッシュの式はここ1本。**
 *
 * ■なぜ1本にしたのか
 *   まったく同じ31進のループが6か所（gameStore 3・playerUtils 1・playerGenerator 1・clubs 1）に
 *   コピーされていた。「選手IDから引退年齢を決める」「選手IDから能力のゆらぎを決める」
 *   「クラブIDからGM名を決める」は全部これで、片方だけ触ると **同じセーブの選手が別人になる**。
 *
 * ■戻り値
 *   32ビットの符号なし整数（0 〜 4294967295）。`% n` がそのまま使えるように符号なしにしてある。
 *   `Math.abs(h | 0)` で読んでいる古い呼び出しが3つあるが（能力のゆらぎ・GM名・海外の上限）、
 *   あちらは**既に配られた選手の数値を変えないため**に符号ありで畳んでいる。
 *   計算そのものはこの関数1本なので、式を変えれば両方に効く。**新しく書くときは符号なしのまま使うこと。**
 */
export function strHash(s: string): number {
  let h = 0
  for (let i = 0; i < s.length; i++) h = (Math.imul(h, 31) + s.charCodeAt(i)) >>> 0
  return h >>> 0
}
