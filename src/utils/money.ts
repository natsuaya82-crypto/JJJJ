// 金額表示の「唯一の決まり」。
//
// yen >= 1億は「X.X億」、それ未満は「X万」に切り捨てる表示が、13ファイル・14箇所に
// 手書きコピーされていた。SponsorPage.tsx だけ億に切り上げず「52,000万」のように
// 万のまま出す別ルールで、同じ金額が画面によって表記が変わっていた
// （これは意図した統一なのでここに寄せた）。
//
// ★ 金額を表示したくなったら、必ずここの fmtYen を使うこと。新しく関数を書かないこと。

/** 円→「X.X億」/「X万」表示。1億未満は万を四捨五入。接頭辞・接尾辞は呼び出し側で付ける。 */
export function fmtYen(yen: number): string {
  if (yen >= 100000000) return `${(yen / 100000000).toFixed(1)}億`
  return `${Math.round(yen / 10000)}万`
}
